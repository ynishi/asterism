//! The `chapter_scan` reading path against real files and real storage:
//! an ffmpeg that actually opens a container, and rows that actually
//! land in an imported band.
//!
//! The parser's own grammar is covered by unit tests beside it
//! (`jobs::chapter_ffmetadata`), over strings. What those cannot tell
//! anybody is whether the strings are the ones ffmpeg prints — and on
//! the Matroska fixture they are emphatically not what a reader would
//! guess: the file is *written* with millisecond chapter times and comes
//! back declaring `TIMEBASE=1/1000000000`, so a parser that assumed
//! milliseconds would be wrong by a factor of a million on the first
//! real file it met. That is the gap this file exists to close.
//!
//! # Fixtures, and the numbers being managed twice
//!
//! `chaptered.mkv` and `chaptered.m4a` are generated by
//! `scripts/gen-test-fixtures.py`, which declares the same timings this
//! file asserts. The duplication is deliberate and is the header of that
//! script's standing policy: a test that read its expectations out of
//! the fixture would pass against a fixture with no chapters at all.
//!
//! Every other media fixture in the workspace is a negative case here,
//! and one of them is asserted as such below — "declares no chapters"
//! and "could not be read" are different outcomes and only one of them
//! leaves a band behind.
//!
//! # No skip when ffmpeg is missing
//!
//! These panic with the install instruction instead, following
//! `thumb_ffmpeg`'s fixture test: a skipped gate reads as a passed one
//! in a summary line, and this repository has no CI to notice the
//! difference.

